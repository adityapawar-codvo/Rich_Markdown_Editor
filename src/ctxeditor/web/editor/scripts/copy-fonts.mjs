// Copies the self-hosted fonts (SIL OFL, from @fontsource-variable) into the app's static folder and writes
// fonts.css. Run once when fonts change: `npm run fonts`. No font is ever requested from a third party.
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../static/fonts");
mkdirSync(out, { recursive: true });

const FONTS = [
  { family: "Inter", pkg: "inter", file: "inter-latin-wght-normal.woff2", weight: "100 900", style: "normal" },
  { family: "Source Serif 4", pkg: "source-serif-4", file: "source-serif-4-latin-wght-normal.woff2", weight: "200 900", style: "normal" },
  { family: "Source Serif 4", pkg: "source-serif-4", file: "source-serif-4-latin-wght-italic.woff2", weight: "200 900", style: "italic" },
  { family: "JetBrains Mono", pkg: "jetbrains-mono", file: "jetbrains-mono-latin-wght-normal.woff2", weight: "100 800", style: "normal" },
];

let css = "/* Self-hosted fonts (SIL Open Font License). Generated by scripts/copy-fonts.mjs */\n";
for (const f of FONTS) {
  const src = resolve(here, `../node_modules/@fontsource-variable/${f.pkg}/files/${f.file}`);
  copyFileSync(src, resolve(out, f.file));
  css += `@font-face{font-family:"${f.family}";font-style:${f.style};font-weight:${f.weight};font-display:swap;src:url("fonts/${f.file}") format("woff2");}\n`;
}
writeFileSync(resolve(out, "../fonts.css"), css);
console.log("fonts copied");
